# Solstice FDE - guided credential setup
# Run it as many times as you like. It only asks for what is still missing,
# and it saves to .env immediately after every single paste.
#
#   powershell -ExecutionPolicy Bypass -File setup.ps1           # fill what's missing
#   powershell -ExecutionPolicy Bypass -File setup.ps1 -Status   # just show me what I have
#   powershell -ExecutionPolicy Bypass -File setup.ps1 -Force    # re-ask everything

param(
    [switch]$Status,
    [switch]$Force,
    [string[]]$Only   # e.g. -Only TELNYX_API_KEY   (re-asks just that one, even if already set)
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Definition
$envPath = Join-Path $root '.env'

